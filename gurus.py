def cik_list(value):
    """GURUS 값(문자열 또는 리스트)을 10자리 CIK 리스트로 변환"""
    vals = value if isinstance(value, (list, tuple)) else [value]
    return [str(v).strip().zfill(10) for v in vals if str(v).strip()]
